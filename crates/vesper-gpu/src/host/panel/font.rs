/// Width in logical pixels for a string drawn with `px` glyph scale.
pub(super) fn text_width(text: &str, px: u32) -> u32 {
    let n = text.len() as u32;
    if n == 0 {
        0
    } else {
        n * (GLYPH.0 + 1) * px - px
    }
}

/// Draw vector anti-aliased rounded hero numerals (`0-9`, `.`, `-`) at `(x, y)` with height `h`.
/// Returns total advance width in pixels.
pub(super) fn draw_hero_numerals(c: &mut Canvas, mut x: f32, y: f32, h: f32, color: [u8; 3], s: &str) -> f32 {
    let dw = h * 0.54;
    let gap = h * 0.16;
    let t = (h * 0.145).max(2.0);
    let r = t * 0.55;
    let m = h * 0.5;
    // 7 segments: top, top-left, top-right, mid, bot-left, bot-right, bot
    let start_x = x;
    for ch in s.bytes() {
        if ch == b'.' {
            c.circle_aa(x + t * 0.5, y + h - t * 0.65, t * 0.58, color, 1.0);
            x += t * 1.15 + gap * 0.7;
            continue;
        }
        if ch == b' ' {
            x += dw * 0.5;
            continue;
        }
        let mask: u8 = match ch {
            b'0' => 0b1110111,
            b'1' => 0b0010010,
            b'2' => 0b1011101,
            b'3' => 0b1011011,
            b'4' => 0b0111010,
            b'5' => 0b1101011,
            b'6' => 0b1101111,
            b'7' => 0b1010010,
            b'8' => 0b1111111,
            b'9' => 0b1111011,
            b'-' => 0b0001000,
            _ => 0,
        };
        let lx = x + r;
        let rx = x + dw - r;
        let ty = y + r;
        let my = y + m;
        let by = y + h - r;
        let seg = |canvas: &mut Canvas, x0: f32, y0: f32, x1: f32, y1: f32| {
            canvas.line_aa(x0, y0, x1, y1, t, color, 1.0);
        };
        if mask & 0b1000000 != 0 {
            seg(c, lx + 1.0, ty, rx - 1.0, ty);
        }
        if mask & 0b0100000 != 0 {
            seg(c, lx, ty + 1.0, lx, my - 1.0);
        }
        if mask & 0b0010000 != 0 {
            seg(c, rx, ty + 1.0, rx, my - 1.0);
        }
        if mask & 0b0001000 != 0 {
            seg(c, lx + 1.0, my, rx - 1.0, my);
        }
        if mask & 0b0000100 != 0 {
            seg(c, lx, my + 1.0, lx, by - 1.0);
        }
        if mask & 0b0000010 != 0 {
            seg(c, rx, my + 1.0, rx, by - 1.0);
        }
        if mask & 0b0000001 != 0 {
            seg(c, lx + 1.0, by, rx - 1.0, by);
        }
        x += dw + gap;
    }
    x - start_x
}
